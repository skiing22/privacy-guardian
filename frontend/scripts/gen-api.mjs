// Generates src/api/schema.d.ts from the backend's OpenAPI schema (AGENTS.md 7.2).
// Run from frontend/ with the backend's Python environment active: npm run gen:api
// CI runs it and fails if the committed file is out of date.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const py = process.env.PYTHON ?? 'python'
const schema = execFileSync(
  py,
  ['-c', 'import json; from app.main import create_app; print(json.dumps(create_app().openapi()))'],
  { cwd: '../backend', encoding: 'utf8' },
)
const ast = await openapiTS(JSON.parse(schema))
const banner = '// Generated by `npm run gen:api` from the backend OpenAPI schema. Do not edit.\n'
writeFileSync('src/api/schema.d.ts', banner + astToString(ast))
console.log('wrote src/api/schema.d.ts')
